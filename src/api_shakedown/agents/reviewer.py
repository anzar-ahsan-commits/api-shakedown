"""Agent that reviews the other specialists' output.

Code already guarantees validity (schemas, routing, ids); the reviewer judges what code
cannot: realism, coverage, and whether expectations make sense. Findings are either
blockers (reject: the author revises) or suggestions (approve with comments), and every
finding must cite a real item in the artifact, so hallucinated complaints are fed back
and dropped rather than triggering pointless revisions.
"""

import json
from collections.abc import Callable
from dataclasses import dataclass
from typing import Any, Literal

from agentpanel import AgentContext, Artifact, Verdict
from langchain_core.language_models import BaseChatModel
from pydantic import BaseModel, Field

from api_shakedown.agents._common import generate_checked
from api_shakedown.chaos import ChaosSuite
from api_shakedown.contracts import ContractSuite
from api_shakedown.spec import ApiSpec, Operation
from api_shakedown.testdata import Dataset
from api_shakedown.wiremock import RECORD_PRIORITY, StubSet

GENERAL = "general"
MAX_CHARS = 16_000
MAX_VALUE_CHARS = 300

INSTRUCTIONS = """\
You review artifacts generated for an API test harness. Validity (schemas, routing, \
ids) is already checked by code; you judge quality.

Report only real problems, each about one specific item, with a concrete fix:
- "blocker": the artifact would be wrong or misleading for its purpose; the author \
must fix it.
- "suggestion": an improvement that is not required.
If the artifact is good, return an empty findings list. Do not invent problems.

OpenAPI note: "default" and ranges such as "4XX" are valid response keys. "default" \
means any status the spec does not list explicitly, so a case that expects "default" \
passes for any such status (400, 500, ...)."""

CHECKLISTS = {
    "stubs": """\
Checklist for WireMock stubs:
- Bodies look like real data: no placeholders such as "string", "foo", or "test".
- Ids and names are consistent across operations.
- Error bodies match their status and plausibly describe the failure.
- Response headers have plausible values.
Request matching (paths, priorities, which stub answers which request) is generated by \
code and is correct; judge only the response content.""",
    "contracts": """\
Checklist for contract test cases:
- Each operation has a happy path, its documented error statuses where feasible, and \
boundary cases for constrained inputs.
- Each case's inputs would actually produce its expected status (a 400 case must send \
invalid input; a 404 case an unknown id).
- Inputs are realistic; there are no near-duplicate cases.""",
    "chaos": """\
Checklist for chaos scenarios:
- Scenarios are realistic and valuable for this API (writes, most-used reads, \
retries, partial failure).
- Each expectation is concrete and matches its effect (e.g. retry advice only for \
transient failures).
- No two scenarios test the same thing.
Baseline scenarios and probes are generated by code and cannot be changed by the \
author: only suggest about them, never block.""",
    "dataset": """\
Checklist for test data:
- Records are realistic and varied: no placeholders, enum values spread across records.
- Data is internally consistent (names, dates, amounts, references).""",
}


class Finding(BaseModel):
    severity: Literal["blocker", "suggestion"]
    item: str = Field(description='Id of the stub/case/scenario/record, or "general".')
    problem: str
    fix: str = Field(description="The concrete change the author should make.")


class ReviewFindings(BaseModel):
    findings: list[Finding] = Field(default_factory=list)


@dataclass
class ArtifactReviewer:
    model: BaseChatModel
    name: str = "reviewer"
    max_findings: int = 8
    max_attempts: int = 3

    async def review(self, artifact: Artifact, ctx: AgentContext) -> Verdict:
        spec: ApiSpec = ctx.inputs["spec"]
        reviewable = describe(artifact.content)
        if reviewable is None:
            return Verdict(approved=True, comments=["Not reviewed: unknown artifact type."])
        kind, rendering, items, blockable = reviewable
        notes: list[str] = []
        output = await generate_checked(
            self.model,
            f"{INSTRUCTIONS}\n\n{CHECKLISTS[kind]}",
            _prompt(spec, artifact, rendering, items),
            ReviewFindings,
            check=lambda out: _problems(out, items),
            max_attempts=self.max_attempts,
            notes=notes,
        )
        if output is None:
            return Verdict(approved=True, comments=[f"Review unavailable: {' '.join(notes)}"])
        findings = [
            _downgrade(f, blockable) for f in output.findings if not _finding_problems(f, items)
        ]
        findings.sort(key=lambda f: f.severity != "blocker")
        findings = findings[: self.max_findings]
        return Verdict(
            approved=not any(f.severity == "blocker" for f in findings),
            comments=[f"[{f.severity}] {f.item}: {f.problem} Fix: {f.fix}" for f in findings],
        )


Rendered = tuple[list[str], set[str], set[str]]  # lines, citable ids, blockable ids


def describe(content: Any) -> tuple[str, str, set[str], set[str]] | None:
    """(checklist kind, rendering, citable ids, ids the author can fix) for an artifact."""
    renderers: list[tuple[type, str, Callable[[Any], Rendered]]] = [
        (StubSet, "stubs", _stubs),
        (ContractSuite, "contracts", _contracts),
        (ChaosSuite, "chaos", _chaos),
        (Dataset, "dataset", _dataset),
    ]
    for model, kind, render in renderers:
        if isinstance(content, model):
            lines, items, blockable = render(content)
            return kind, _fit(lines), items, blockable
    return None


def _stubs(stubs: StubSet) -> Rendered:
    lines = [
        "(Which stub answers which request is decided by code and is correct; the bracket "
        "says when each one is used. The X-Shakedown-Status header is a deliberate test "
        "hook, not part of the API: it lets tests request each documented response on "
        "demand. Never report it as a problem.)"
    ]
    for m in stubs.mappings:
        request, response = m["request"], m["response"]
        meta = m["metadata"]["shakedown"]
        body = response.get("jsonBody", response.get("body"))
        lines.append(
            f"- {m['name']}: {request['method']} [{_when(m, meta)}] "
            f"-> {response.get('status')} {_short(body)}"
        )
    items = {m["name"] for m in stubs.mappings}
    items |= {m["metadata"]["shakedown"]["operationId"] for m in stubs.mappings}
    # Bodies taken from the test dataset are not the stub author's to change.
    from_dataset = {
        m["name"] for m in stubs.mappings if m["metadata"]["shakedown"].get("source") == "dataset"
    }
    return lines, items, items - from_dataset


def _when(mapping: dict[str, Any], meta: dict[str, Any]) -> str:
    if meta.get("selectedBy"):
        header, value = next(iter(meta["selectedBy"].items()))
        meaning = " (the spec's 'default' response)" if value == "default" else ""
        return f"only when the client sends {header}: {value}{meaning}"
    if mapping["priority"] == RECORD_PRIORITY:
        return f"only for {mapping['name'].split(' ', 2)[2]} (a record in the test data)"
    if mapping["name"].endswith("(unknown id)"):
        return "for ids not in the test data"
    return "normal response"


def _contracts(suite: ContractSuite) -> Rendered:
    lines = [
        f"- {c.id}: {c.method.upper()} {c.path} path={_short(c.path_params)} "
        f"query={_short(c.query)} body={_short(c.body)} -> expect {_status(c.expected_status)}"
        for c in suite.cases
    ]
    items = {c.id for c in suite.cases} | {c.operation_id for c in suite.cases}
    return lines, items, items


def _status(label: str) -> str:
    if label == "default":
        return "default (any status the spec does not list explicitly)"
    if not label.isdigit():
        return f"{label} (any {label[0]}xx)"
    return label


def _chaos(suite: ChaosSuite) -> Rendered:
    lines = ["Scenarios:"] + [
        f"- {s.id} [{s.category}, {'baseline, fixed' if s.source == 'baseline' else 'llm'}] "
        f"ops={s.operations or 'all'} "
        f"effect={_short(s.effect.model_dump(exclude_none=True))} times={s.times} "
        f"| expect: {s.expectation}"
        for s in suite.scenarios
    ]
    per_op: dict[str, list[str]] = {}
    for probe in suite.probes:
        per_op.setdefault(probe.operation_id, []).append(probe.description)
    lines.append("Robustness probes (malformed requests that must get a 4xx):")
    lines += [f"- {op}: {len(d)} probes, e.g. {'; '.join(d[:4])}" for op, d in per_op.items()]
    items = {s.id for s in suite.scenarios} | {p.id for p in suite.probes} | set(per_op)
    blockable = {s.id for s in suite.scenarios if s.source == "llm"} | set(per_op)
    return lines, items, blockable


def _dataset(dataset: Dataset) -> Rendered:
    lines: list[str] = []
    items: set[str] = set()
    for entity in dataset.entities.values():
        items.add(entity.name)
        for record in entity.records:
            ref = f"{entity.name}#{record.get(entity.id_field or '', '?')}"
            items.add(ref)
            lines.append(f"- {ref}: {_short(record)}")
    return lines, items, items


def _prompt(spec: ApiSpec, artifact: Artifact, rendering: str, items: set[str]) -> str:
    operations = "\n".join(_operation_line(op) for op in spec.operations)
    return (
        f"API: {spec.title} {spec.version}\nOperations:\n{operations}\n\n"
        f"Review this {artifact.kind} produced by '{artifact.author}':\n"
        f"<artifact>\n{rendering}\n</artifact>\n\n"
        'Each finding\'s "item" must be one of the ids shown above (the text before the '
        'colon on a line, or an operation id), or "general" for a suggestion.'
    )


def _operation_line(op: Operation) -> str:
    """One line per operation, with the inputs a reviewer needs to judge cases."""
    params = ", ".join(
        f"{p.name} ({p.location}{', required' if p.required else ''}"
        + (f", {_short(_constraints(p.schema_))}" if _constraints(p.schema_) else "")
        + ")"
        for p in op.parameters
    )
    body = ""
    if op.request_body is not None:
        body = f" body: {op.request_body.content_type}"
        body += " (required)" if op.request_body.required else " (optional)"
    return (
        f"- {op.id}: {op.method.upper()} {op.path}"
        + (f" ({op.summary})" if op.summary else "")
        + (f" params: {params};" if params else " no params;")
        + (body or " no request body;")
        + f" statuses {[r.status for r in op.responses]}"
    )


def _constraints(schema: dict[str, Any] | None) -> dict[str, Any]:
    keys = ("type", "enum", "minimum", "maximum", "minLength", "maxLength", "format")
    return {k: v for k, v in (schema or {}).items() if k in keys}


def _downgrade(finding: Finding, blockable: set[str]) -> Finding:
    """A blocker on something the author cannot change becomes a suggestion."""
    if finding.severity == "blocker" and finding.item not in blockable:
        return finding.model_copy(update={"severity": "suggestion"})
    return finding


def _problems(output: ReviewFindings, items: set[str]) -> list[str]:
    return [
        f"finding about {finding.item!r}: {problem}"
        for finding in output.findings
        for problem in _finding_problems(finding, items)
    ]


def _finding_problems(finding: Finding, items: set[str]) -> list[str]:
    if finding.item == GENERAL:
        if finding.severity == "blocker":
            return ["a blocker must name a specific item, not 'general'."]
        return []
    if finding.item not in items:
        return ["item is not in the artifact; cite an id exactly as shown."]
    return []


def _short(value: Any) -> str:
    text = json.dumps(value, default=str, ensure_ascii=False)
    return text if len(text) <= MAX_VALUE_CHARS else text[:MAX_VALUE_CHARS] + "...(truncated)"


def _fit(lines: list[str]) -> str:
    kept: list[str] = []
    size = 0
    for line in lines:
        if size + len(line) > MAX_CHARS:
            kept.append(f"... ({len(lines) - len(kept)} more lines omitted)")
            break
        kept.append(line)
        size += len(line) + 1
    return "\n".join(kept)
